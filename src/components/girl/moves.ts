function dayNumber(date: Date): number {
  return Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
}

function wrap(value: number, size: number): number {
  return ((value % size) + size) % size;
}

function hash(day: number, salt: number): number {
  let value = (day * 2654435761 + salt * 40503) >>> 0;
  value = Math.imul(value ^ (value >>> 15), 2246822519) >>> 0;
  value = Math.imul(value ^ (value >>> 13), 3266489917) >>> 0;
  return (value ^ (value >>> 16)) >>> 0;
}

export function pickGirl(kind: GirlKind, mood: 'happy' | 'sad', slot: number, date = new Date()) {
  const day = dayNumber(date);
  const list = MOVE_LISTS[kind][mood];
  const index = wrap(day * 7 + slot * 17 + (mood === 'sad' ? 11 : 0), list.length);
  const wears = WEAR_BY_KIND[kind];
  const top = TOPS[wrap(hash(day, 1) + slot * 7, TOPS.length)];
  let bottom = BOTTOMS[wrap(hash(day, 2) + slot * 3, BOTTOMS.length)];
  if (bottom === top) bottom = BOTTOMS[0];
  return {
    index,
    move: list[index],
    outfit: {
      dress: top,
      bottom,
      skin: SKINS[wrap(hash(day, 3) + slot, SKINS.length)],
      hair: HAIR_COLORS[wrap(hash(day, 4) + slot * 2, HAIR_COLORS.length)],
      shoe: `color-mix(in srgb, ${top} 60%, #1a1a1a)`,
    },
    print: PRINTS[wrap(hash(day, 5) + slot * 3, PRINTS.length)],
    hair: HAIRS[wrap(hash(day, 6) + slot * 2, HAIRS.length)],
    wear: wears[wrap(hash(day, 7) + slot * 2, wears.length)],
  };
}
