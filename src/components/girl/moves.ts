function fill<T extends Common>(bases: T[], alts: Fx[][], vary: (move: T, round: number) => T = (move) => move): T[] {
  const out = [...bases];
  for (let index = 0; out.length < SIZE; index += 1) {
    const base = bases[index % bases.length];
    const round = Math.floor(index / bases.length) + 1;
    const fx = alts[(index + round) % alts.length];
    if (fx.join() === base.fx.join()) continue;
    const swaps = FACE_SWAPS[base.face] ?? [base.face];
    const face = swaps[(index + round) % swaps.length];
    out.push(vary({ ...base, name: `${base.name}~${round}`, fx, face }, round));
  }
  return out.slice(0, SIZE);
}

